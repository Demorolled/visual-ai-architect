/**
 * render-reference.mjs — turn the narration map into a readable reference doc.
 *
 * The map is the single source of truth: the same strings that get spoken are
 * the ones documented here, so the written reference cannot drift from what the
 * app says. Regenerate after editing narrationMap.ts.
 *
 *   node docs/narration/render-reference.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const mapPath = join(here, '..', '..', 'frontend', 'src', 'narration', 'narrationMap.ts');

// Node strips the TypeScript type annotations on import, so the map can be read
// directly rather than duplicated into JSON.
const { NARRATION } = await import(mapPath);

const WORDS_PER_SECOND = 2.6;
const normalize = (s) =>
  (s || '')
    .toLowerCase()
    .replace(/[\u{1F000}-\u{1FFFF}\u{2190}-\u{2BFF}\u{2600}-\u{27BF}\u{FE0F}\u{200D}]/gu, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

const seconds = (text) => Math.round((text.split(/\s+/).length / WORDS_PER_SECOND) * 10) / 10;
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

const rows = NARRATION.map((e) => ({
  ...e,
  secs: seconds(e.text),
  keys: [...new Set([e.title, ...(e.match || [])].map(normalize).filter(Boolean))],
}));

const total = rows.reduce((a, r) => a + r.secs, 0);

let md = `# VACA control narration — reference

Generated from \`frontend/src/narration/narrationMap.ts\` by
\`docs/narration/render-reference.mjs\`. **Do not edit this file**; edit the map.

${rows.length} controls. Spoken length at ~${WORDS_PER_SECOND} words/second:
**${mmss(total)} total**, longest single entry **${mmss(Math.max(...rows.map((r) => r.secs)))}**.

Every entry was traced through the source. The \`source\` line is where the claim
came from, so it can be re-checked after a refactor.

## How a hover resolves

The pointer must rest on a control for **450 ms**. It then narrates **once** per
hover, even though the browser fires \`mouseover\` again on every child element.
Keys are matched in this order, and the first one that hits an entry wins:

1. \`data-narration\` attribute
2. \`aria-label\`
3. \`title\`
4. visible text (emoji and punctuation stripped)
5. visible text with counts/parentheticals removed — so \`Fix All (3)\` still
   resolves once the build has failing files
6. \`className\`

If two entries share a label, the one carrying \`requireClass\` must also see that
class **as a whole class token** on the element. Substring matching is
deliberately avoided: \`settings-save-btn\` contains \`save-btn\`.

## Entries

| control | speaks | matched by | source |
|---|---|---|---|
`;

for (const r of rows) {
  const qualifier = r.requireClass ? ` *(class: \`${r.requireClass}\`)*` : '';
  md += `| **${r.title}** | ${mmss(r.secs)} | ${r.keys.map((k) => `\`${k}\``).join(', ')}${qualifier} | \`${r.source}\` |\n`;
}

md += `\n## Spoken text\n\n`;

for (const r of rows) {
  md += `### ${r.title}\n\n`;
  md += `- **id:** \`${r.id}\`\n`;
  md += `- **length:** ${r.secs}s (${r.text.split(/\\s+/).length} words)\n`;
  md += `- **source:** \`${r.source}\`\n`;
  if (r.requireClass) md += `- **requires class:** \`${r.requireClass}\`\n`;
  md += `\n> ${r.text}\n\n`;
}

const out = join(here, 'CONTROLS.md');
writeFileSync(out, md, 'utf8');
console.log(`wrote ${out}`);
console.log(`${rows.length} entries, ${mmss(total)} of speech total`);
const longest = [...rows].sort((a, b) => b.secs - a.secs).slice(0, 8);
console.log('longest:');
for (const r of longest) console.log(`  ${mmss(r.secs).padStart(5)}  ${r.id}`);
